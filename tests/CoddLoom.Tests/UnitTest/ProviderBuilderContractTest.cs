    [TestMethod]
    public void ColumnTypes_CoverEverySupportedDbType_ForEveryProvider()
    {
        foreach (var provider in Enum.GetValues<Provider>())
        {
            var builder = CreateBuilder(provider);
            foreach (var dbType in SupportedDbTypes)
            {
                Assert.AreEqual(ExpectedColumnType(provider, dbType), builder.ColumnType(dbType),
                    $"Unexpected mapping for {provider}/{dbType}.");
            }

            Assert.ThrowsExactly<NotSupportedException>(() => builder.ColumnType((DbType)int.MaxValue),
                $"{provider} must reject DbType values it cannot persist safely.");
        }
    }

    [TestMethod]
    public void SpecializedColumns_UseEachProviderNativeSyntax()
    {
        AssertCreateSql(Provider.Sqlite,
            "id INTEGER PRIMARY KEY AUTOINCREMENT",
            "code TEXT NOT NULL", "fixedCode TEXT", "payload BLOB", "amount REAL");
        AssertCreateSql(Provider.MySql,
            "id BIGINT AUTO_INCREMENT PRIMARY KEY NOT NULL",
            "code VARCHAR(32) CHARACTER SET utf8mb4 NOT NULL",
            "fixedCode CHAR(8) CHARACTER SET latin1", "payload BLOB", "amount DECIMAL(12,3)");
        AssertCreateSql(Provider.MariaDb,
            "id BIGINT AUTO_INCREMENT PRIMARY KEY NOT NULL",
            "code VARCHAR(32) CHARACTER SET utf8mb4 NOT NULL",
            "fixedCode CHAR(8) CHARACTER SET latin1", "payload BLOB", "amount DECIMAL(12,3)");
        AssertCreateSql(Provider.SqlServer,
            "id BIGINT IDENTITY(1,1) PRIMARY KEY NOT NULL",
            "code NVARCHAR(32) NOT NULL", "fixedCode CHAR(8)", "payload VARBINARY(3000)",
            "amount DECIMAL(12,3)");
        AssertCreateSql(Provider.Oracle,
            "id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL",
            "code NVARCHAR2(32) NOT NULL", "fixedCode CHAR(8)", "payload BLOB", "amount NUMBER(12,3)");
        AssertCreateSql(Provider.PostgreSql,
            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL",
            "code VARCHAR(32) NOT NULL", "fixedCode CHAR(8)", "payload BYTEA", "amount NUMERIC(12,3)");
    }

    [TestMethod]
    public void Pagination_UsesProviderSpecificSyntax()
    {
        var page = new PageParam { PageNumber = 3, PageSize = 10 };
        var orderBy = new OrderByCondition("id");

        Assert.AreEqual("SELECT * FROM sample ORDER BY id ASC LIMIT 20,10", CreateBuilder(Provider.Sqlite).Select(page, orderBy));
        Assert.AreEqual("SELECT * FROM sample ORDER BY id ASC LIMIT 20,10", CreateBuilder(Provider.MySql).Select(page, orderBy));
        Assert.AreEqual("SELECT * FROM sample ORDER BY id ASC LIMIT 20,10", CreateBuilder(Provider.MariaDb).Select(page, orderBy));
        Assert.AreEqual("SELECT * FROM sample ORDER BY id ASC OFFSET 20 ROWS FETCH NEXT 10 ROWS ONLY",
            CreateBuilder(Provider.SqlServer).Select(page, orderBy));
        Assert.AreEqual("SELECT * FROM sample ORDER BY id ASC OFFSET 20 ROWS FETCH NEXT 10 ROWS ONLY",
            CreateBuilder(Provider.Oracle).Select(page, orderBy));
        Assert.AreEqual("SELECT * FROM sample ORDER BY id ASC LIMIT 10 OFFSET 20",
            CreateBuilder(Provider.PostgreSql).Select(page, orderBy));
    }

    [TestMethod]
    public void SqlServerPagination_SuppliesRequiredFallbackOrdering()
    {
        var builder = new SqlServerBuilder();
        var page = new PageParam { PageNumber = 1, PageSize = 10 };

        Assert.AreEqual(
            "SELECT * FROM sample ORDER BY (SELECT NULL) ASC OFFSET 0 ROWS FETCH NEXT 10 ROWS ONLY",
            builder.Select("sample", pageParam: page));
        Assert.AreEqual(
            "SELECT * FROM sample ORDER BY (SELECT NULL) ASC OFFSET 0 ROWS FETCH NEXT 10 ROWS ONLY",
            builder.Select("sample", new WhereConditions(), pageParam: page));

        var where = new WhereConditions("tenantId", 1);
        Assert.AreEqual(
            "SELECT * FROM sample WHERE tenantId = @tenantId0 ORDER BY tenantId ASC OFFSET 0 ROWS FETCH NEXT 10 ROWS ONLY",
            builder.Select("sample", where, pageParam: page));
    }

    [TestMethod]
    public void DropTable_UsesProviderCompatibleSyntax()
    {
        foreach (var provider in Enum.GetValues<Provider>())
        {
            var expected = provider == Provider.Oracle
                ? "DROP TABLE sample"
                : "DROP TABLE IF EXISTS sample";
            Assert.AreEqual(expected, CreateBuilder(provider).DropTable("sample"), provider.ToString());
        }
    }

    [TestMethod]
    public void DateTimeCast_UsesProviderCompatibleSyntax()
    {
        foreach (var provider in Enum.GetValues<Provider>())
        {
            var expected = provider switch
            {
                Provider.MySql or Provider.MariaDb or Provider.SqlServer => "CAST(createdAt AS DATETIME)",
                Provider.Oracle or Provider.PostgreSql => "CAST(createdAt AS TIMESTAMP)",
                _ => "CAST(createdAt AS DateTime)"
            };
            Assert.AreEqual(expected, CreateBuilder(provider).Cast("createdAt", DbType.DateTime), provider.ToString());
            Assert.ThrowsExactly<NotSupportedException>(() => CreateBuilder(provider).Cast("createdAt", DbType.Guid));
        }
    }

    [TestMethod]
    public void ParameterMarkers_UseProviderCompatiblePrefixes()
    {
        foreach (var provider in Enum.GetValues<Provider>())
        {
            var expected = provider == Provider.Oracle ? ":value" : "@value";
            Assert.AreEqual(expected, CreateBuilder(provider).ParameterName(new ValueParam(1, "value")));
        }
    }

    [TestMethod]
    public void OracleBatchInsert_UsesPre23CompatibleInsertAllSyntax()
    {
        var rows = new[]
        {
            new InputValues().Add("id", 1).Add("name", "one"),
            new InputValues().Add("name", "two").Add("id", 2)
        };

        var sql = new OracleBuilder().Insert("sample", rows, out var parameters);

        Assert.AreEqual(
            "INSERT ALL INTO sample (id,name) VALUES (:V0_id,:V0_name) "
            + "INTO sample (id,name) VALUES (:V1_id,:V1_name) SELECT 1 FROM DUAL",
            sql);
        CollectionAssert.AreEqual(
            new object[] { 1, "one", 2, "two" },
            parameters.Select(parameter => parameter.Value).ToArray());
    }

