    private static void AssertCreateSql(Provider provider, params string[] expectedFragments)
    {
        var sql = CreateBuilder(provider).CreateTable(new TableDefine(typeof(AllColumnShapesTable)));
        foreach (var expected in expectedFragments)
        {
            StringAssert.Contains(sql, expected, $"{provider}: {sql}");
        }
    }

