    private static IExposedBuilder CreateBuilder(Provider provider) => provider switch
    {
        Provider.Sqlite => new ExposedSqlBuilder(),
        Provider.MySql => new ExposedMySqlBuilder(),
        Provider.MariaDb => new ExposedMariaDbBuilder(),
        Provider.SqlServer => new ExposedSqlServerBuilder(),
        Provider.Oracle => new ExposedOracleBuilder(),
        Provider.PostgreSql => new ExposedPostgreSqlBuilder(),
        _ => throw new AssertFailedException(provider.ToString())
    };

    private interface IExposedBuilder
    {
        string ColumnType(DbType type);
        string CreateTable(TableDefine table);
        string Select(PageParam page, OrderByCondition orderBy);
        string DropTable(string tableName);
        string Cast(string column, DbType type);
        string ParameterName(ValueParam parameter);
    }

    private sealed class ExposedSqlBuilder : SqlBuilder, IExposedBuilder
    {
        public string ColumnType(DbType type) => base.GetColumnType(type);
        public string CreateTable(TableDefine table) => base.GetCreateTableSql(table);
        public string Select(PageParam page, OrderByCondition orderBy) => base.Select("sample", orderBy: orderBy, pageParam: page);
        public string DropTable(string tableName) => base.DropTableSql(tableName);
        public string Cast(string column, DbType type) => base.GetCastColumn(column, type);
        public string ParameterName(ValueParam parameter) => base.GetParamName(parameter);
    }

